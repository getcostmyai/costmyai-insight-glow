import { createClient } from "@supabase/supabase-js";
import { mintApiKey, revokeApiKey } from "../../src/lib/ingest/keys.server";
const URL=process.env["SUPABASE_URL"]!,S=process.env["SUPABASE_SERVICE_ROLE_KEY"]!,P=process.env["SUPABASE_PUBLISHABLE_KEY"]!;
const admin=createClient(URL,S,{auth:{persistSession:false}});
const stamp=Date.now(), email=`journey6-ui2-${stamp}@costmyai-test.dev`, password="Journey-6-UI-2026!";
const u=await admin.auth.admin.createUser({email,password,email_confirm:true}); if(u.error) throw u.error;
const c=createClient(URL,P,{auth:{persistSession:false}}); await c.auth.signInWithPassword({email,password});
const org=(await c.rpc("create_organization",{_name:`Journey 6 UI ${stamp}`})).data as string;
const k=await mintApiKey(org,"proof",u.data.user!.id);
const now=Date.now();
const events=Array.from({length:240},(_,i)=>({occurred_at:new Date(now-i*900_000).toISOString(),model_key:"openai/gpt-4o-mini",host:"openai",task_hint:"generation" as const,input_tokens:2400+(i%7)*120,output_tokens:700+(i%5)*40,latency_ms:910,status:"ok" as const,idempotency_key:`p2-${stamp}-${i}`}));
const r=await fetch("http://localhost:8080/api/public/v1/events",{method:"POST",headers:{"content-type":"application/json",authorization:`Bearer ${k.token}`},body:JSON.stringify({v:1,events})});
console.log("push",r.status,await r.text());
await revokeApiKey(org,k.id);
console.log(JSON.stringify({email,org,userId:u.data.user!.id}));
