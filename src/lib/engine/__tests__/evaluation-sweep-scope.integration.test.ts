/**
 * The scope of the evaluation sweep, asserted directly instead of inferred.
 *
 * `opts.orgIds` was added to `runEvaluation` so the synthetic harnesses could
 * run the REAL writer over their own disposable workspace. The production cron
 * passes nothing and must keep sweeping every workspace. Nothing tested that
 * claim: it rested on a two-line diff and on an unrelated test happening to
 * report a plausible org count.
 *
 * So this file asserts the omitted path two independent ways, because either
 * one alone is weak evidence:
 *
 *  1. The wire. Global fetch is captured for the duration of the run and the
 *     actual PostgREST request for `organizations` is inspected. A filter would
 *     appear as an `id=in.(...)` query parameter. Its absence is the proof that
 *     no filter was attached — not the source reading as though none was.
 *  2. The outcome, by identity. The org ids returned to the engine are read off
 *     the wire and compared against the ids that existed both immediately
 *     before and immediately after the run. Every such id must have been swept.

 *
 * And the empty array is pinned on purpose. It is a caller bug, so the guard
 * throws before any query is issued — asserted here both by the throw itself
 * and by zero captured requests, so a future silent zero-sweep cannot return
 * unnoticed.
 */
import { createClient } from "@supabase/supabase-js";
import { afterAll, beforeAll, describe, expect, it } from "vitest";

import { runEvaluation } from "@/lib/engine/evaluate.server";

import { guardIntegrationDatabase } from "../../__tests__/support/isolation";

const URL = process.env["SUPABASE_URL"]!;
const SERVICE = process.env["SUPABASE_SERVICE_ROLE_KEY"]!;

const admin = createClient(URL, SERVICE, {
  auth: { persistSession: false, autoRefreshToken: false },
});
guardIntegrationDatabase(admin);

/** Every PostgREST URL hit while a capture is armed. */
let captured: string[] = [];

/** Requests this run made against the organizations table. */
function organizationRequests(): string[] {
  return captured.filter((u) => u.includes("/rest/v1/organizations"));
}

/** Org ids returned to the engine by the sweep's own organizations read. */
let sweptOrgIds: string[] = [];

async function withFetchCapture<T>(fn: () => Promise<T>): Promise<{ result: T; urls: string[] }> {
  const real = globalThis.fetch;
  captured = [];
  sweptOrgIds = [];
  globalThis.fetch = (async (input: Parameters<typeof fetch>[0], init?: Parameters<typeof fetch>[1]) => {
    const url =
      typeof input === "string"
        ? input
        : input instanceof Request
          ? input.url
          : String(input);
    captured.push(url);
    const response = await real(input as never, init as never);
    if (url.includes("/rest/v1/organizations")) {
      // Read the body the engine is about to receive. Every row it returns is
      // evaluated, so this IS the set of workspaces the sweep touched.
      try {
        const rows = (await response.clone().json()) as Array<{ id?: string }>;
        if (Array.isArray(rows)) {
          for (const row of rows) if (row?.id) sweptOrgIds.push(row.id);
        }
      } catch {
        /* head/count requests have no JSON body */
      }
    }
    return response;
  }) as typeof fetch;
  try {
    const result = await fn();
    return { result, urls: [...captured] };
  } finally {
    globalThis.fetch = real;
  }
}

/** Org ids present immediately before / immediately after the sweep. */
let orgIdsBefore: string[] = [];
let orgIdsAfter: string[] = [];
let sweptIds: string[] = [];

let unfiltered: Awaited<ReturnType<typeof runEvaluation>>;
let unfilteredOrgUrls: string[] = [];
let emptyArrayError: unknown = null;
let emptyArrayUrls: string[] = [];

async function orgIds(synthetic: boolean): Promise<string[]> {
  const { data, error } = await admin
    .from("organizations")
    .select("id")
    .eq("is_synthetic", synthetic);
  if (error) throw error;
  return (data ?? []).map((row) => row.id as string);
}

let syntheticIds: string[] = [];

beforeAll(async () => {
  // Ids, not counts. Other integration suites create and tear down disposable
  // workspaces in parallel, so any total counted outside the sweep is a moving
  // target. The provable claim is about identity: whichever workspaces existed
  // for the WHOLE window must all have been swept.
  // Synthetic workspaces are excluded from the sweep by design (test fixtures
  // must not have recommendation rows regenerated by the scheduled writer), so
  // the identity claim only covers is_synthetic=false workspaces, and the
  // synthetic set is asserted as swept-out below.
  orgIdsBefore = await orgIds(false);
  syntheticIds = await orgIds(true);

  // No second argument at all — byte-for-byte how both cron routes call it.
  const run = await withFetchCapture(() => runEvaluation(`sweep-scope-unfiltered-${Date.now()}`));
  unfiltered = run.result;
  unfilteredOrgUrls = run.urls.filter((u) => u.includes("/rest/v1/organizations"));
  sweptIds = [...sweptOrgIds];

  orgIdsAfter = await orgIds();
  console.log(
    `[scope] organizations before=${orgIdsBefore.length} after=${orgIdsAfter.length} swept=${sweptIds.length}`,
  );


  // The empty array must be refused before anything is queried, so the capture
  // has to survive the throw to prove no request went out.
  const real = globalThis.fetch;
  captured = [];
  globalThis.fetch = ((input: Parameters<typeof fetch>[0], init?: Parameters<typeof fetch>[1]) => {
    captured.push(typeof input === "string" ? input : input instanceof Request ? input.url : String(input));
    return real(input as never, init as never);
  }) as typeof fetch;
  try {
    await runEvaluation(`sweep-scope-empty-${Date.now()}`, { orgIds: [] });
    emptyArrayError = null;
  } catch (err) {
    emptyArrayError = err;
  } finally {
    emptyArrayUrls = [...captured];
    globalThis.fetch = real;
  }
}, 300_000);

afterAll(() => {
  globalThis.fetch = globalThis.fetch;
});

describe("runEvaluation with no options, exactly as the cron calls it", () => {
  it("issues an organizations query with no id filter on the wire", () => {
    expect(unfilteredOrgUrls.length).toBeGreaterThan(0);
    const [url] = unfilteredOrgUrls;
    console.log(`[unfiltered] ${decodeURIComponent(url!)}`);
    // A narrowed sweep would carry `id=in.(...)`. Nothing else in this query
    // can produce that parameter.
    expect(decodeURIComponent(url!)).not.toContain("id=in.");
    expect(url!).not.toContain("id=in.");
  });

  it("selects the same four columns the evaluator reads, unchanged", () => {
    const url = decodeURIComponent(unfilteredOrgUrls[0]!);
    expect(url).toContain("select=id,plan,is_synthetic,autonomous_enabled");
  });

  it("evaluates every organization that existed for the whole run", () => {
    const after = new Set(orgIdsAfter);
    const stable = orgIdsBefore.filter((id) => after.has(id));
    const swept = new Set(sweptIds);
    const missed = stable.filter((id) => !swept.has(id));
    console.log(
      `[unfiltered] report.orgs=${unfiltered.orgs} swept=${swept.size} stable=${stable.length} missed=${missed.length}`,
    );
    // Orgs created or torn down by concurrent suites during the window are
    // excluded on purpose: no claim about them is provable. No upper bound is
    // asserted for the same reason.
    expect(stable.length).toBeGreaterThan(1);
    expect(missed).toEqual([]);
    expect(unfiltered.orgs).toBe(swept.size);
  });


  it("reaches those workspaces without erroring on any of them", () => {
    expect(unfiltered.errors).toEqual([]);
  });
});

describe("runEvaluation({ orgIds: [] }) is refused as a caller error", () => {
  it("throws instead of sweeping nobody", () => {
    console.log(`[empty] threw: ${String(emptyArrayError)}`);
    expect(emptyArrayError).toBeInstanceOf(Error);
  });

  it("says plainly that an empty array is a caller error, not an instruction", () => {
    const message = (emptyArrayError as Error).message;
    expect(message).toContain("empty array");
    expect(message).toContain("caller error");
    expect(message).toContain("Omit orgIds");
  });

  it("emits no query at all before refusing", () => {
    console.log(`[empty] requests captured: ${emptyArrayUrls.length}`);
    expect(emptyArrayUrls.filter((u) => u.includes("/rest/v1/organizations"))).toEqual([]);
    // Not just the organizations read — nothing whatsoever went out.
    expect(emptyArrayUrls).toEqual([]);
  });
});
